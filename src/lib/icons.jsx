// Own-property lookup so keys like "constructor" or "__proto__" (which the
// server accepts as brand keys) can't resolve to Object.prototype members.
export function getBrand(key) {
  return typeof key === 'string' && Object.prototype.hasOwnProperty.call(BRAND_ICONS, key)
    ? BRAND_ICONS[key]
    : null
}

export function detectService(nameOrIssuer = '') {
  if (!nameOrIssuer) return null
  for (const { match, key } of MATCH_RULES) {
    if (match.test(nameOrIssuer)) return key
  }
  return null
}

const GRADIENTS = [
  ['#4f46e5', '#7c3aed'],
  ['#2563eb', '#06b6d4'],
  ['#059669', '#10b981'],
  ['#d97706', '#f59e0b'],
  ['#dc2626', '#f43f5e'],
  ['#db2777', '#c026d3'],
  ['#0891b2', '#3b82f6'],
  ['#7c2d12', '#ea580c'],
]

function getGradient(str = '') {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash)
  }
  const idx = Math.abs(hash) % GRADIENTS.length
  return `linear-gradient(135deg, ${GRADIENTS[idx][0]}, ${GRADIENTS[idx][1]})`
}

function getInitials(str = '') {
  const clean = str.trim().replace(/^https?:\/\//i, '')
  if (!clean) return '•'
  const parts = clean.split(/[\s:_-]+/)
  if (parts.length >= 2 && parts[0] && parts[1]) {
    return (parts[0][0] + parts[1][0]).toUpperCase()
  }
  return clean.slice(0, 2).toUpperCase()
}

export function ServiceLogo({
  logo,
  issuer = '',
  label = '',
  size = 38,
  className = '',
  style = {},
  onError,
  onLoad,
}) {
  const [imgError, setImgError] = useState(false)

  // 1. Explicit URL or data URI
  const isUrl = typeof logo === 'string' && /^(https?:\/\/|data:image\/)/i.test(logo)

  // Reset the failure flag whenever the source changes. Without this, picking a
  // broken URL (e.g. a host with hotlink protection) permanently latched the
  // component into the monogram fallback, so every later upload/URL in the same
  // mounted component silently failed too.
  useEffect(() => {
    setImgError(false)
  }, [logo])

  if (isUrl && !imgError) {
    return (
      <div
        className={`service-logo ${className}`}
        style={{
          width: size,
          height: size,
          minWidth: size,
          borderRadius: 8,
          overflow: 'hidden',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          background: 'var(--panel-2)',
          border: '1px solid var(--border)',
          ...style,
        }}
      >
        <img
          src={logo}
          alt={issuer || label}
          referrerPolicy="no-referrer"
          loading="lazy"
          onLoad={() => onLoad?.(logo)}
          onError={() => {
            setImgError(true)
            onError?.(logo)
          }}
          style={{ width: '100%', height: '100%', objectFit: 'contain' }}
        />
      </div>
    )
  }

  // 2. Preset key or auto-detect
  const brandKey = getBrand(logo)
    ? logo
    : detectService(issuer) || detectService(label)

  // A stored URL that failed to load is not a brand key, so skip straight to
  // the monogram rather than re-detecting a service from the label.
  const failedUrl = isUrl && imgError
  if (!failedUrl && brandKey && getBrand(brandKey)) {
    const brand = getBrand(brandKey)
    return (
      <div
        className={`service-logo ${className}`}
        title={brand.name}
        style={{
          width: size,
          height: size,
          minWidth: size,
          borderRadius: 8,
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          background: brand.bg || 'var(--panel-2)',
          color: brand.color || 'var(--text)',
          border: '1px solid var(--border)',
          padding: size * 0.2,
          ...style,
        }}
      >
        {brand.svg}
      </div>
    )
  }

  // 3. Monogram fallback avatar
  const displayName = issuer || label || '2FA'
  const initials = getInitials(displayName)
  const bg = getGradient(displayName)

  return (
    <div
      className={`service-logo monogram ${className}`}
      style={{
        width: size,
        height: size,
        minWidth: size,
        borderRadius: 8,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        background: bg,
        color: '#ffffff',
        fontWeight: 700,
        fontSize: size * 0.38,
        letterSpacing: -0.5,
        userSelect: 'none',
        border: '1px solid rgba(255,255,255,0.15)',
        ...style,
      }}
    >
      {initials}
    </div>
  )
}
